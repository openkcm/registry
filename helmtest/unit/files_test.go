// The tests in this file check the files that values.yaml documents: they write each file
// in the documented format, at its documented path below a temporary directory, and read it
// with the code that the Registry uses for it. Examples of file content are taken from the
// comments of values.yaml; certificates and keys are generated by the tests.

// valuesComment returns the commented example of values.yaml below the line that ends with
// marker: the following comment lines that are indented by at least three spaces after the
// comment sign, without the comment sign and these three spaces.
func valuesComment(t *testing.T, marker string) string {
	t.Helper()

	values, err := os.ReadFile(chartPath + "/values.yaml")
	require.NoError(t, err)

	lines := strings.Split(string(values), "\n")

	var example []string

	for i, line := range lines {
		if !strings.HasSuffix(line, marker) {
			continue
		}

		require.Nil(t, example, "more than one line of values.yaml ends with %q", marker)

		before, _, found := strings.Cut(line, "#")
		require.True(t, found, "%q is not in a comment of values.yaml", marker)

		example = []string{}

		for _, next := range lines[i+1:] {
			text, ok := strings.CutPrefix(next, before+"#   ")
			if !ok {
				break
			}

			example = append(example, text)
		}

		require.NotEmpty(t, example, "no example below %q in values.yaml", marker)
	}

	require.NotNil(t, example, "no line of values.yaml ends with %q", marker)

	return strings.Join(example, "\n") + "\n"
}

// fileRoot is a temporary directory that stands for the root directory of the container:
// the files of the documented paths, such as /etc/otel/tls.crt, are created below it.
type fileRoot string

func newFileRoot(t *testing.T) fileRoot {
	t.Helper()
	return fileRoot(t.TempDir())
}

// path returns the path below the root for a path in the container.
func (r fileRoot) path(containerPath string) string {
	return filepath.Join(string(r), containerPath)
}

// write creates the file of a path in the container.
func (r fileRoot) write(t *testing.T, containerPath string, content []byte) {
	t.Helper()

	path := r.path(containerPath)
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
	require.NoError(t, os.WriteFile(path, content, 0o600))
}

// ref returns the value reference with its file below the root.
func (r fileRoot) ref(t *testing.T, ref commoncfg.SourceRef) commoncfg.SourceRef {
	t.Helper()
	require.Equal(t, commoncfg.FileSourceValue, ref.Source)

	ref.File.Path = r.path(ref.File.Path)

	return ref
}

// loadValues renders the chart with the values file and loads the configuration the way the
// Registry does at startup.
func loadValues(t *testing.T, args ...string) *config.Config {
	t.Helper()

	cfg, err := loadConfig(t, renderConfigYAML(t, args...))
	require.NoError(t, err)

	return cfg
}

// TestFilesDatabaseCredentials checks the files of config.database.user and password: a
// file with only the value (format binary) and a JSON document (format json with jsonPath).
// The Registry writes the values into the connection string (GetDataSourceName), which the
// database driver parses.
func TestFilesDatabaseCredentials(t *testing.T) {
	tests := []struct {
		name   string
		values string
		files  map[string]string
	}{
		{
			name:   "files with only the value",
			values: "testdata/values-all-config.yaml",
			files: map[string]string{
				"/etc/credentials/database/username": "registry",
				// A trailing newline, as `echo` writes it, is ignored here.
				"/etc/credentials/database/password": "<password>\n",
			},
		},
		{
			name:   "JSON document",
			values: "testdata/values-all-config-alt2.yaml",
			files: map[string]string{
				"/etc/credentials/database/db.json": valuesComment(t,
					"content of /etc/credentials/database/db.json:"),
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := newFileRoot(t)
			for path, content := range tt.files {
				root.write(t, path, []byte(content))
			}

			db := loadValues(t, "-f", tt.values).Database
			db.User = root.ref(t, db.User)
			db.Password = root.ref(t, db.Password)

			dsn, err := sql.GetDataSourceName(db)
			require.NoError(t, err)

			pgConfig, err := pgx.ParseConfig(dsn)
			require.NoError(t, err)
			assert.Equal(t, "registry", pgConfig.User)
			assert.Equal(t, "<password>", pgConfig.Password)
		})
	}

	t.Run("jsonPath", func(t *testing.T) {
		tests := []struct {
			name     string
			content  string
			jsonPath string
			want     string
			wantErr  bool
		}{
			{
				name:     "field",
				content:  `{"password": "<password>"}`,
				jsonPath: "$.password",
				want:     "<password>",
			},
			{
				name:     "nested field",
				content:  `{"registry": {"password": "<password>"}}`,
				jsonPath: "$.registry.password",
				want:     "<password>",
			},
			{
				name:     "a number is not a string",
				content:  `{"password": 1234}`,
				jsonPath: "$.password",
				wantErr:  true,
			},
		}

		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				path := filepath.Join(t.TempDir(), "db.json")
				require.NoError(t, os.WriteFile(path, []byte(tt.content), 0o600))

				value, err := commoncfg.LoadValueFromSourceRef(commoncfg.SourceRef{
					Source: commoncfg.FileSourceValue,
					File: commoncfg.CredentialFile{
						Path: path, Format: commoncfg.JSONFileFormat, JSONPath: tt.jsonPath,
					},
				})
				if tt.wantErr {
					require.Error(t, err)
					return
				}

				require.NoError(t, err)
				assert.Equal(t, tt.want, string(value))
			})
		}
	})
}

var errNoSSLRequest = errors.New("the client sent no SSLRequest")

// postgresSSLRequest answers the SSLRequest with which a PostgreSQL client starts TLS.
func postgresSSLRequest(conn net.Conn) error {
	var request [2]int32

	err := binary.Read(conn, binary.BigEndian, &request)
	if err != nil {
		return err
	}

	if request != [2]int32{8, 80877103} {
		return errNoSSLRequest
	}

	_, err = conn.Write([]byte{'S'})

	return err
}

// TestFilesDatabaseTLS checks the files of the PGSSL* variables of the example in values.yaml
// (config.database): the Registry connects to a test server with them, the way it does at
// startup (sql.StartDB).
func TestFilesDatabaseTLS(t *testing.T) {
	pki := newTestPKI(t)

	var example struct {
		ExtraEnvs []struct {
			Name  string `yaml:"name"`
			Value string `yaml:"value"`
		} `yaml:"extraEnvs"`
	}

	require.NoError(t, yaml.Unmarshal(
		[]byte(valuesComment(t, "Example of the TLS variables in `extraEnvs`:")), &example))
	require.Len(t, example.ExtraEnvs, 4)

	// connect writes the files and starts the database connection of the Registry with the
	// variables of the example. The test server presents a certificate for serverName and
	// ends the connection after the TLS handshake.
	connect := func(t *testing.T, format keyFormat, serverName string) (handshake, error) {
		t.Helper()

		root := newFileRoot(t)
		crt, key, ca := pki.clientFiles(t, format)
		root.write(t, "/etc/credentials/database/username", []byte("registry"))
		root.write(t, "/etc/credentials/database/password", []byte("<password>"))
		root.write(t, "/etc/credentials/database/tls.crt", crt)
		root.write(t, "/etc/credentials/database/tls.key", key)
		root.write(t, "/etc/credentials/database/ca.crt", ca)

		for _, env := range example.ExtraEnvs {
			value := env.Value
			if strings.HasPrefix(value, "/") {
				value = root.path(value)
			}

			t.Setenv(env.Name, value)
		}

		t.Setenv("PGCONNECT_TIMEOUT", "10")

		port, results := serveTLS(t, pki.server(t, serverName), pki.rootPool(), postgresSSLRequest)

		db := loadValues(t, "-f", "testdata/values-all-config.yaml",
			"--set", "config.database.host=localhost",
			"--set", "config.database.port="+port).Database
		db.User = root.ref(t, db.User)
		db.Password = root.ref(t, db.Password)

		_, err := sql.StartDB(t.Context(), db)
		require.Error(t, err, "the test server ends the connection after the TLS handshake")

		return firstHandshake(t, results), err
	}

	for _, format := range keyFormats {
		t.Run("tls.key "+format.name, func(t *testing.T) {
			result, _ := connect(t, format, "localhost")
			require.NoError(t, result.err)
			require.Len(t, result.chain, 2, "client certificate and intermediate CA")
			assert.Equal(t, "registry", result.chain[0].Subject.CommonName)
		})
	}

	t.Run("server certificate for another host", func(t *testing.T) {
		_, err := connect(t, keyFormats[0], "postgresql.example.com")
		require.ErrorContains(t, err,
			"certificate is valid for postgresql.example.com, not localhost")
	})

	t.Run("PGSSLROOTCERT system", func(t *testing.T) {
		t.Setenv("PGSSLMODE", "require")
		t.Setenv("PGSSLROOTCERT", "system")

		dsn, err := sql.GetDataSourceName(loadValues(t,
			"--set", "config.database.host=postgresql.services.svc.cluster.local",
			"--set", "config.database.user.value=registry",
			"--set", "config.database.password.value=<password>",
		).Database)
		require.NoError(t, err)

		pgConfig, err := pgx.ParseConfig(dsn)
		require.NoError(t, err)
		require.NotNil(t, pgConfig.TLSConfig)
		assert.False(t, pgConfig.TLSConfig.InsecureSkipVerify, "the server certificate is verified")
		assert.Equal(t, "postgresql.services.svc.cluster.local", pgConfig.TLSConfig.ServerName)
		assert.Empty(t, pgConfig.Fallbacks, "no connection without TLS")
	})
}

// TestFilesOrbitalMTLS checks the mtls files of an orbital target (values-all-config.yaml):
// the Registry connects with them to a test broker the way it does at startup
// (internal/service/orbital.go).
func TestFilesOrbitalMTLS(t *testing.T) {
	pki := newTestPKI(t)

	target := loadValues(t, "-f", "testdata/values-all-config.yaml").Orbital.Targets[0]
	mtls := target.Connection.Auth.MTLS
	require.Equal(t, config.AuthTypeMTLS, target.Connection.Auth.Type)

	// connect writes the files and connects to url. Test brokers speak no AMQP, so the
	// connection always fails after the TLS handshake.
	connect := func(t *testing.T, url string, crt, key, ca []byte) error {
		t.Helper()

		root := newFileRoot(t)
		root.write(t, mtls.CertFile, crt)
		root.write(t, mtls.KeyFile, key)
		root.write(t, mtls.CAFile, ca)

		ctx, cancel := context.WithTimeout(t.Context(), 15*time.Second)
		defer cancel()

		connInfo := amqp.ConnectionInfo{
			URL:    url,
			Target: target.Connection.AMQP.Target,
			Source: target.Connection.AMQP.Source,
		}
		option := amqp.WithExternalMTLS(
			root.path(mtls.CertFile), root.path(mtls.KeyFile), root.path(mtls.CAFile), "")

		client, err := amqp.NewClient(ctx, &codec.Proto{}, connInfo, option)
		if client != nil {
			_ = client.Close(ctx)
		}

		return err
	}

	for _, format := range keyFormats {
		t.Run("tls.key "+format.name, func(t *testing.T) {
			port, results := serveTLS(t, pki.server(t, "localhost"), pki.rootPool(), nil)
			crt, key, ca := pki.clientFiles(t, format)

			require.Error(t, connect(t, "amqps://localhost:"+port, crt, key, ca))

			result := firstHandshake(t, results)
			require.NoError(t, result.err)
			require.Len(t, result.chain, 2, "client certificate and intermediate CA")
			assert.Equal(t, "registry", result.chain[0].Subject.CommonName)
		})
	}

	t.Run("tls.crt without the intermediate CA", func(t *testing.T) {
		port, results := serveTLS(t, pki.server(t, "localhost"), pki.rootPool(), nil)
		crt, key, ca := pki.clientFiles(t, keyFormats[1])
		leaf, _ := pem.Decode(crt)

		require.Error(t, connect(t, "amqps://localhost:"+port, pem.EncodeToMemory(leaf), key, ca))
		require.Error(t, firstHandshake(t, results).err, "the broker cannot verify the client")
	})

	t.Run("broker certificate for another host", func(t *testing.T) {
		port, _ := serveTLS(t, pki.server(t, "rabbitmq.example.com"), pki.rootPool(), nil)
		crt, key, ca := pki.clientFiles(t, keyFormats[1])

		err := connect(t, "amqps://localhost:"+port, crt, key, ca)
		require.ErrorContains(t, err,
			"certificate is valid for rabbitmq.example.com, not localhost")
	})

	t.Run("ca.crt without the CA of the broker", func(t *testing.T) {
		port, _ := serveTLS(t, pki.server(t, "localhost"), pki.rootPool(), nil)
		crt, key, _ := pki.clientFiles(t, keyFormats[1])

		err := connect(t, "amqps://localhost:"+port, crt, key, certPEM(pki.other.cert))
		require.ErrorContains(t, err, "certificate signed by unknown authority")
	})

	t.Run("ca.crt without a certificate", func(t *testing.T) {
		crt, key, _ := pki.clientFiles(t, keyFormats[1])

		err := connect(t, "amqps://localhost:5671", crt, key, key)
		require.ErrorIs(t, err, amqp.ErrInvalidCACert)
	})

	t.Run("tls.key of another certificate", func(t *testing.T) {
		crt, _, ca := pki.clientFiles(t, keyFormats[1])
		_, otherKey, _ := pki.clientFiles(t, keyFormats[1])

		err := connect(t, "amqps://localhost:5671", crt, otherKey, ca)
		require.ErrorIs(t, err, amqp.ErrTLSPairLoad)
	})

	t.Run("amqp:// URL", func(t *testing.T) {
		listener, err := net.Listen("tcp", "127.0.0.1:0")
		require.NoError(t, err)
		t.Cleanup(func() { _ = listener.Close() })

		header := make(chan []byte, 1)

		go func() {
			conn, err := listener.Accept()
			if err != nil {
				return
			}
			defer func() { _ = conn.Close() }()

			_ = conn.SetDeadline(time.Now().Add(10 * time.Second))
			buf := make([]byte, 8)
			_, _ = io.ReadFull(conn, buf)
			header <- buf
		}()

		_, port, err := net.SplitHostPort(listener.Addr().String())
		require.NoError(t, err)

		crt, key, ca := pki.clientFiles(t, keyFormats[1])
		require.Error(t, connect(t, "amqp://localhost:"+port, crt, key, ca))

		// The client starts with the AMQP SASL header in plain text, not with TLS.
		select {
		case got := <-header:
			assert.Equal(t, []byte("AMQP\x03\x01\x00\x00"), got)
		case <-time.After(15 * time.Second):
			t.Fatal("the client did not connect")
		}
	})
}

// collector starts an HTTPS test server with the certificate that requires a client
// certificate issued by a CA in clientCAs, and returns its URL with the host name localhost.
func collector(t *testing.T, cert tls.Certificate, clientCAs *x509.CertPool) string {
	t.Helper()

	server := httptest.NewUnstartedServer(
		http.HandlerFunc(func(http.ResponseWriter, *http.Request) {}))
	server.TLS = &tls.Config{
		Certificates: []tls.Certificate{cert},
		ClientAuth:   tls.RequireAndVerifyClientCert,
		ClientCAs:    clientCAs,
		MinVersion:   tls.VersionTLS12,
	}
	server.StartTLS()
	t.Cleanup(server.Close)

	_, port, err := net.SplitHostPort(server.Listener.Addr().String())
	require.NoError(t, err)

	return "https://localhost:" + port
}

// TestFilesTelemetry checks the files of the telemetry examples of values.yaml
// (values-all-config*.yaml), read with the common-sdk functions that the OpenTelemetry
// exporters of the Registry use.
func TestFilesTelemetry(t *testing.T) {
	pki := newTestPKI(t)

	// mtlsConfig writes the client files of the mtls settings and loads them.
	mtlsConfig := func(t *testing.T, mtls commoncfg.MTLS, format keyFormat) *tls.Config {
		t.Helper()

		root := newFileRoot(t)
		crt, key, ca := pki.clientFiles(t, format)
		root.write(t, mtls.Cert.File.Path, crt)
		root.write(t, mtls.CertKey.File.Path, key)
		mtls.Cert = root.ref(t, mtls.Cert)
		mtls.CertKey = root.ref(t, mtls.CertKey)

		if mtls.ServerCA != nil {
			root.write(t, mtls.ServerCA.File.Path, ca)
			serverCA := root.ref(t, *mtls.ServerCA)
			mtls.ServerCA = &serverCA
		}

		for i, rootCA := range mtls.RootCAs {
			root.write(t, rootCA.File.Path, ca)
			mtls.RootCAs[i] = root.ref(t, rootCA)
		}

		tlsConfig, err := commoncfg.LoadMTLSConfig(&mtls)
		require.NoError(t, err)

		return tlsConfig
	}

	get := func(t *testing.T, tlsConfig *tls.Config, url string) error {
		t.Helper()

		client := &http.Client{Transport: &http.Transport{TLSClientConfig: tlsConfig}}

		resp, err := client.Get(url)
		if err != nil {
			return err
		}

		return resp.Body.Close()
	}

	t.Run("mtls with serverCa", func(t *testing.T) {
		telemetry := loadValues(t, "-f", "testdata/values-all-config.yaml").Telemetry
		mtls := telemetry.Traces.SecretRef.MTLS
		require.NotNil(t, mtls.ServerCA)

		url := collector(t, pki.server(t, "localhost"), pki.rootPool())

		for _, format := range keyFormats {
			t.Run("tls.key "+format.name, func(t *testing.T) {
				require.NoError(t, get(t, mtlsConfig(t, mtls, format), url))
			})
		}
	})

	t.Run("mtls with rootCAs and serverName", func(t *testing.T) {
		telemetry := loadValues(t, "-f", "testdata/values-all-config-alt2.yaml").Telemetry
		mtls := telemetry.Traces.SecretRef.MTLS
		require.Len(t, mtls.RootCAs, 1)
		require.Equal(t, "otel-collector.example.com", mtls.Attributes.ServerName)

		url := collector(t, pki.server(t, "otel-collector.example.com"), pki.rootPool())
		require.NoError(t, get(t, mtlsConfig(t, mtls, keyFormats[1]), url))
	})

	t.Run("api-token", func(t *testing.T) {
		telemetry := loadValues(t, "-f", "testdata/values-all-config.yaml").Telemetry
		apiToken := telemetry.Metrics.SecretRef.APIToken

		var authorization string

		server := httptest.NewServer(http.HandlerFunc(func(_ http.ResponseWriter, r *http.Request) {
			authorization = r.Header.Get("Authorization")
		}))
		t.Cleanup(server.Close)

		root := newFileRoot(t)
		root.write(t, apiToken.File.Path, []byte("<token>"))

		ref := root.ref(t, apiToken)

		client, err := commonhttp.NewClientFromAPIToken(&ref)
		require.NoError(t, err)

		resp, err := client.Get(server.URL)
		require.NoError(t, err)
		require.NoError(t, resp.Body.Close())
		assert.Equal(t, "Api-Token <token>", authorization)

		// A trailing newline is part of the token, and the request fails.
		root.write(t, apiToken.File.Path, []byte("<token>\n"))

		client, err = commonhttp.NewClientFromAPIToken(&ref)
		require.NoError(t, err)

		_, err = client.Get(server.URL) //nolint:bodyclose // the request fails
		require.ErrorContains(t, err, "invalid header field value")
	})

	t.Run("basic password", func(t *testing.T) {
		telemetry := loadValues(t, "-f", "testdata/values-all-config-alt1.yaml").Telemetry
		basic := telemetry.Traces.SecretRef.Basic

		root := newFileRoot(t)
		root.write(t, basic.Password.File.Path, []byte("<password>"))

		password, err := commoncfg.LoadValueFromSourceRef(root.ref(t, basic.Password))
		require.NoError(t, err)
		assert.Equal(t, "<password>", string(password))
	})
}

// TestFilesMountExample renders the chart with the example of extraVolumes and
// extraVolumeMounts in values.yaml, and checks that every file of the examples in
// values.yaml is in one of the mounted Secrets.
func TestFilesMountExample(t *testing.T) {
	example := "extraVolumes:\n" + valuesComment(t, "Example of the volumes:") +
		"extraVolumeMounts:\n" + valuesComment(t, "Example of the mounts for the volumes above:")

	values := filepath.Join(t.TempDir(), "values.yaml")
	require.NoError(t, os.WriteFile(values, []byte(example), 0o600))

	var rendered struct {
		Spec struct {
			Template struct {
				Spec struct {
					Containers []struct {
						VolumeMounts []struct {
							Name      string `yaml:"name"`
							MountPath string `yaml:"mountPath"`
							ReadOnly  bool   `yaml:"readOnly"`
						} `yaml:"volumeMounts"`
					} `yaml:"containers"`
					Volumes []struct {
						Name   string `yaml:"name"`
						Secret *struct {
							SecretName  string `yaml:"secretName"`
							DefaultMode int    `yaml:"defaultMode"`
						} `yaml:"secret"`
					} `yaml:"volumes"`
				} `yaml:"spec"`
			} `yaml:"template"`
		} `yaml:"spec"`
	}

	object(t, render(t, "-f", values), "Deployment", &rendered)

	secrets := map[string]bool{}

	for _, volume := range rendered.Spec.Template.Spec.Volumes {
		if volume.Secret != nil {
			secrets[volume.Name] = true

			assert.Equal(t, 0o440, volume.Secret.DefaultMode, "defaultMode of %s", volume.Name)
		}
	}

	require.Len(t, secrets, 3)

	var mountPaths []string

	for _, mount := range rendered.Spec.Template.Spec.Containers[0].VolumeMounts {
		if secrets[mount.Name] {
			mountPaths = append(mountPaths, mount.MountPath)

			assert.True(t, mount.ReadOnly, "mount of %s", mount.Name)
		}
	}

	require.Len(t, mountPaths, 3)

	for _, path := range documentedFiles(t) {
		assert.True(t, slices.ContainsFunc(mountPaths, func(mountPath string) bool {
			return strings.HasPrefix(path, mountPath+"/")
		}), "%s is not in a mounted Secret", path)
	}
}

// documentedFiles returns the paths of all files in the examples of values.yaml: the files
// of the testdata values (one per documented example) and of the PGSSL* variables.
func documentedFiles(t *testing.T) []string {
	t.Helper()

	var paths []string

	addRef := func(ref commoncfg.SourceRef) {
		if ref.Source == commoncfg.FileSourceValue {
			paths = append(paths, ref.File.Path)
		}
	}

	addSecretRef := func(secretRef commoncfg.SecretRef) {
		addRef(secretRef.APIToken)
		addRef(secretRef.Basic.Username)
		addRef(secretRef.Basic.Password)
		addRef(secretRef.MTLS.Cert)
		addRef(secretRef.MTLS.CertKey)

		if secretRef.MTLS.ServerCA != nil {
			addRef(*secretRef.MTLS.ServerCA)
		}

		for _, rootCA := range secretRef.MTLS.RootCAs {
			addRef(rootCA)
		}
	}

	for _, values := range []string{
		"testdata/values-all-config.yaml",
		"testdata/values-all-config-alt1.yaml",
		"testdata/values-all-config-alt2.yaml",
	} {
		cfg := loadValues(t, "-f", values)
		addRef(cfg.Database.User)
		addRef(cfg.Database.Password)

		for _, target := range cfg.Orbital.Targets {
			if mtls := target.Connection.Auth.MTLS; mtls != nil {
				paths = append(paths, mtls.CertFile, mtls.KeyFile, mtls.CAFile)
			}
		}

		telemetry := cfg.Telemetry
		addRef(telemetry.Traces.Host)
		addRef(telemetry.Metrics.Host)
		addRef(telemetry.Logs.Host)
		addSecretRef(telemetry.Traces.SecretRef)
		addSecretRef(telemetry.Metrics.SecretRef)
		addSecretRef(telemetry.Logs.SecretRef)
	}

	var example struct {
		ExtraEnvs []struct {
			Value string `yaml:"value"`
		} `yaml:"extraEnvs"`
	}

	require.NoError(t, yaml.Unmarshal(
		[]byte(valuesComment(t, "Example of the TLS variables in `extraEnvs`:")), &example))

	for _, env := range example.ExtraEnvs {
		if strings.HasPrefix(env.Value, "/") {
			paths = append(paths, env.Value)
		}
	}

	require.Len(t, paths, 18)

	return paths
}
